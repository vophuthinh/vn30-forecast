"""
Baseline check for multiwindow_eval.py results.

Same 5 windows x 30 tickers x 20 days. Compares Kronos zero-shot (from
results/multiwindow/per_window_metrics.csv) against:
  - naive random walk: forecast = last context close (MAPE)
  - always-up: predict every day up (DirAcc, same definition as calc_metrics)
Also bootstraps 95% CI for mean Kronos DirAcc and MAPE gap vs naive.
"""
from pathlib import Path

import numpy as np
import pandas as pd

BASE = Path(__file__).resolve().parent.parent
PROC = BASE / "data" / "processed"
PRED_LEN = 20
# keep in sync with multiwindow_eval.WINDOWS
WINDOWS = [("W1", -100, -80), ("W2", -80, -60), ("W3", -60, -40), ("W4", -40, -20), ("W5", -20, None)]
rng = np.random.default_rng(0)

kr = pd.read_csv(BASE / "results/multiwindow/per_window_metrics.csv")
rows = []
for t in sorted(kr.ticker.unique()):
    close = pd.read_csv(PROC / f"{t}.csv")["close"].to_numpy()
    n = len(close)
    for w, s, e in WINDOWS:
        a, b = n + s, (n + e if e else n)
        actual, last = close[a:b], close[a - 1]
        ext = np.concatenate([[last], actual])
        rows.append({
            "ticker": t, "window": w,
            "naive_mape": np.mean(np.abs(actual - last) / actual) * 100,
            "up_dir": np.mean(np.diff(ext) > 0) * 100,   # always-up DirAcc
        })
df = kr.merge(pd.DataFrame(rows), on=["ticker", "window"])


def boot_ci(x, n=5000):
    x = np.asarray(x)
    m = [rng.choice(x, len(x)).mean() for _ in range(n)]
    return np.percentile(m, [2.5, 97.5])


gap = df.mape - df.naive_mape
out = [
    "# Baseline check (auto-generated by scripts/baseline_eval.py)\n",
    f"Pairs: {len(df)} (30 tickers x 5 windows, Jun-Oct 2026, {PRED_LEN}D each)\n",
    "| Metric | Kronos ZS | Baseline |",
    "|---|---|---|",
    f"| Mean MAPE | {df.mape.mean():.2f}% | naive random walk: {df.naive_mape.mean():.2f}% |",
    f"| Median MAPE | {df.mape.median():.2f}% | naive: {df.naive_mape.median():.2f}% |",
    f"| Mean DirAcc | {df.dir_acc.mean():.1f}% | always-up: {df.up_dir.mean():.1f}%, coin flip: 50% |",
    "",
    f"- Kronos DirAcc 95% CI (bootstrap over pairs): {boot_ci(df.dir_acc)[0]:.1f}% - {boot_ci(df.dir_acc)[1]:.1f}%",
    f"- MAPE gap Kronos - naive: mean {gap.mean():+.2f}pp, 95% CI [{boot_ci(gap)[0]:+.2f}, {boot_ci(gap)[1]:+.2f}]",
    f"- Kronos beats naive MAPE in {(gap < 0).mean() * 100:.0f}% of pairs",
    "",
    "Per window:\n",
    "| Window | Kronos MAPE | Naive MAPE | Kronos Dir | Always-up Dir |",
    "|---|---|---|---|---|",
]
for w, g in df.groupby("window"):
    out.append(f"| {w} | {g.mape.mean():.2f}% | {g.naive_mape.mean():.2f}% | {g.dir_acc.mean():.1f}% | {g.up_dir.mean():.1f}% |")
out += ["", "Per ticker (mean over 5 windows):\n",
        "| Ticker | Kronos MAPE | Naive MAPE | Kronos Dir | Always-up Dir |", "|---|---|---|---|---|"]
for t, g in df.groupby("ticker"):
    out.append(f"| {t} | {g.mape.mean():.2f}% | {g.naive_mape.mean():.2f}% | {g.dir_acc.mean():.1f}% | {g.up_dir.mean():.1f}% |")

p = BASE / "results/analysis/baseline_report.md"
p.write_text("\n".join(out) + "\n")
print("\n".join(out[:16]))
