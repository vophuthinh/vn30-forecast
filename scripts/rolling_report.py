"""
Report on results/rolling/paths.csv (from rolling_eval.py):
  1. Kronos vs naive random walk: MAPE, 20d-return direction, bootstrap CIs
  2. Backtest using the real Kronos signals (no proxy), 20-day holding, 0.1%/side cost:
     long-only, long/short top-5 vs bottom-5, vs equal-weight buy&hold and 5d-momentum
Output: results/analysis/rolling_report.md
"""
from pathlib import Path

import numpy as np
import pandas as pd

BASE = Path(__file__).resolve().parent.parent
TC, PRED_LEN, TOPK = 0.001, 20, 5
rng = np.random.default_rng(0)

d = pd.read_csv(BASE / "results/rolling/paths.csv")
P = d[[f"pred_{i}" for i in range(PRED_LEN)]].to_numpy()
A = d[[f"act_{i}" for i in range(PRED_LEN)]].to_numpy()
last = d.last_ctx_close.to_numpy()[:, None]

d["mape"] = (np.abs(P - A) / A).mean(1) * 100
d["naive_mape"] = (np.abs(last - A) / A).mean(1) * 100
d["pred_ret"] = P[:, -1] / last[:, 0] - 1
d["act_ret"] = A[:, -1] / last[:, 0] - 1
d["dir_hit"] = (np.sign(d.pred_ret) == np.sign(d.act_ret)) * 100
d["up_hit"] = (d.act_ret > 0) * 100
# momentum: 5d return before window start, from the processed series
mom = {}
for t, g in d.groupby("ticker"):
    c = pd.read_csv(BASE / f"data/processed/{t}.csv", parse_dates=["date"]).set_index("date").close
    for _, r in g.iterrows():
        i = c.index.get_loc(pd.Timestamp(r.start_date))
        mom[(t, r.window)] = c.iloc[i - 1] / c.iloc[i - 6] - 1
d["mom5"] = [mom[(t, w)] for t, w in zip(d.ticker, d.window)]


def ci(x, n=5000, w=None):
    """95% bootstrap CI of the mean. With w (window id per value), resample whole windows."""
    x = np.asarray(x, float)
    if w is not None:  # cluster by window: tickers in one window share the market move
        x = pd.Series(x).groupby(np.asarray(w)).mean().to_numpy()
    m = rng.choice(x, (n, len(x))).mean(1)
    return np.percentile(m, [2.5, 97.5])


def fmt(x, p=2, w=None):
    """mean [CI]; window-clustered CI when w (window id per value) is given or x is aligned with `d`."""
    x = pd.Series(x).reset_index(drop=True)
    if w is None and len(x) == len(d):
        w = d.window
    lo, hi = ci(x, w=None if w is None else np.asarray(w))
    return f"{x.mean():.{p}f} [{lo:.{p}f}, {hi:.{p}f}]"


gap = d.mape - d.naive_mape
n_win = d.window.nunique()
out = [f"# Rolling evaluation (auto-generated by scripts/rolling_report.py)\n",
       f"{d.ticker.nunique()} tickers x {n_win} windows x {PRED_LEN}D = {len(d)} pairs, "
       f"{d.start_date.min()} to {d.start_date.max()} (window starts). Zero-shot Kronos-small, 10 samples. "
       "Brackets: 95% bootstrap CI resampling whole windows (all 30 tickers of a window move together, so this is wider than a per-pair bootstrap).\n",
       "## 1. Forecast accuracy\n",
       "| Metric | Kronos | Baseline |", "|---|---|---|",
       f"| MAPE % (mean) | {fmt(d.mape)} | naive random walk {fmt(d.naive_mape)} |",
       f"| MAPE gap Kronos - naive (pp) | {fmt(gap)} | Kronos better in {(gap < 0).mean() * 100:.0f}% of pairs |",
       f"| 20d direction hit % | {fmt(d.dir_hit, 1)} | always-up {fmt(d.up_hit, 1)} ; coin flip 50 |",
       "", "Per ticker (mean over windows):\n",
       "| Ticker | Kronos MAPE | Naive MAPE | Dir hit % | Always-up % |", "|---|---|---|---|---|"]
for t, g in d.groupby("ticker"):
    out.append(f"| {t} | {g.mape.mean():.2f} | {g.naive_mape.mean():.2f} | {g.dir_hit.mean():.1f} | {g.up_hit.mean():.1f} |")

def backtest(tc):
    rows = []
    for k, g in d.groupby("window", sort=False):
        g = g.copy()
        r = g.sort_values("pred_ret")
        m = g.sort_values("mom5")
        rows.append({"window": k, "start": g.start_date.min(), "bh_ew": g.act_ret.mean(),
                     "kronos_long": np.where(g.pred_ret > 0, g.act_ret - 2 * tc, 0.0).mean(),
                     "kronos_ls": 0.5 * (r.act_ret.tail(TOPK).mean() - r.act_ret.head(TOPK).mean()) - 2 * tc,
                     "mom_ls": 0.5 * (m.act_ret.tail(TOPK).mean() - m.act_ret.head(TOPK).mean()) - 2 * tc})
    return pd.DataFrame(rows).sort_values("start")


# ---- backtest: one period = one window; all tickers share window id k (same calendar dates)
rows = []
for k, g in d.groupby("window", sort=False):
    g = g.copy()
    ew = g.act_ret.mean()
    lo = np.where(g.pred_ret > 0, g.act_ret - 2 * TC, 0.0).mean()          # long-only on positive pred
    r = g.sort_values("pred_ret")
    ls = 0.5 * (r.act_ret.tail(TOPK).mean() - r.act_ret.head(TOPK).mean()) - 2 * TC
    m = g.sort_values("mom5")
    ls_mom = 0.5 * (m.act_ret.tail(TOPK).mean() - m.act_ret.head(TOPK).mean()) - 2 * TC
    rows.append({"window": k, "start": g.start_date.min(), "bh_ew": ew, "kronos_long": lo,
                 "kronos_ls": ls, "mom_ls": ls_mom})
bt = pd.DataFrame(rows).sort_values("start")
ppy = 252 / PRED_LEN

out += ["", "## 2. Backtest with real Kronos signals\n",
        f"One period = {PRED_LEN} trading days. Cost {TC * 100:.1f}% per side per trade. "
        f"Long-only = hold stocks with predicted 20d return > 0 (equal weight over all 30, cash otherwise). "
        f"L/S = long top {TOPK}, short bottom {TOPK} by predicted 20d return, dollar-neutral. "
        "Sharpe annualised from period returns. Mean per-period return CI is bootstrap.\n",
        "| Strategy | Total return % | Ann. Sharpe | Mean period % [95% CI] | Max DD % |", "|---|---|---|---|---|"]
for name, col in [("Equal-weight buy & hold", "bh_ew"), ("Kronos long-only", "kronos_long"),
                  ("Kronos L/S", "kronos_ls"), ("5d-momentum L/S (baseline)", "mom_ls")]:
    r = bt[col].to_numpy()
    eq = np.cumprod(1 + r)
    dd = (eq / np.maximum.accumulate(eq) - 1).min() * 100
    sh = r.mean() / r.std(ddof=1) * np.sqrt(ppy) if r.std() > 0 else float("nan")
    out.append(f"| {name} | {(eq[-1] - 1) * 100:.1f} | {sh:.2f} | {fmt(r * 100)} | {dd:.1f} |")
out += ["", "Cost sensitivity (total return %, per side): 0.0% / 0.1% / 0.3% / 0.5%\n", "| Strategy | 0.0% | 0.1% | 0.3% | 0.5% |", "|---|---|---|---|---|"]
sens = {tc: backtest(tc) for tc in (0.0, 0.001, 0.003, 0.005)}
for name, col in [("Kronos long-only", "kronos_long"), ("Kronos L/S", "kronos_ls"), ("5d-momentum L/S", "mom_ls")]:
    out.append(f"| {name} | " + " | ".join(f"{(np.prod(1 + sens[tc][col]) - 1) * 100:.1f}" for tc in sens) + " |")
ex = (bt.kronos_long - bt.bh_ew) * 100
out += ["", f"Kronos long-only minus buy & hold, mean per period: {fmt(ex)} pp over {len(bt)} periods.",
        "", "Per period:\n", "| Start | B&H EW % | Kronos long % | Kronos L/S % | Mom L/S % |", "|---|---|---|---|---|"]
for _, r in bt.iterrows():
    out.append(f"| {r.start} | {r.bh_ew * 100:.1f} | {r.kronos_long * 100:.1f} | {r.kronos_ls * 100:.1f} | {r.mom_ls * 100:.1f} |")

# ---- fine-tuned checkpoint on windows that start after its training cutoff (2025-10-31)
RD = BASE / "results/rolling"
ft_sources = [(f.stem.removeprefix("paths_ft_"), pd.read_csv(f)) for f in sorted(RD.glob("paths_ft_vn30*.csv"))]
grp = sorted(RD.glob("paths_ft_group_*.csv"))
if grp:  # grouped fine-tune (banks / others): one model per group, concatenated
    ft_sources.append(("grouped_v3 (banks + others)", pd.concat([pd.read_csv(f) for f in grp])))
for name, ft in ft_sources:
    key = ["ticker", "window"]
    m = d.merge(ft[key + [f"pred_{i}" for i in range(PRED_LEN)]], on=key, suffixes=("", "_ft"))
    PF = m[[f"pred_{i}_ft" for i in range(PRED_LEN)]].to_numpy()
    Am = m[[f"act_{i}" for i in range(PRED_LEN)]].to_numpy()
    m["ft_mape"] = (np.abs(PF - Am) / Am).mean(1) * 100
    m["ft_dir"] = (np.sign(PF[:, -1] / m.last_ctx_close - 1) == np.sign(m.act_ret)) * 100
    g2 = m.ft_mape - m.mape
    out += ["", f"## 3. Fine-tuned ({name}) vs zero-shot, out-of-training windows only\n",
            (f"{len(m)} pairs (window start >= 2025-11-01). Clean split: train <= 2025-06-30, val 2025-07-01..2025-10-31, test windows never seen.\n" if "cleansplit" in name or "grouped" in name else
             f"{len(m)} pairs (window start >= 2025-11-01; training data ends 2025-10-31 but the val set used for checkpoint selection overlaps these windows, so FT is mildly favoured).\n"),
            "| Metric | Zero-shot | Fine-tuned | Naive |", "|---|---|---|---|",
            f"| MAPE % | {fmt(m.mape, w=m.window)} | {fmt(m.ft_mape, w=m.window)} | {fmt(m.naive_mape, w=m.window)} |",
            f"| 20d direction hit % | {fmt(m.dir_hit, 1, w=m.window)} | {fmt(m.ft_dir, 1, w=m.window)} | always-up {fmt(m.up_hit, 1, w=m.window)} |",
            f"| FT - ZS MAPE (pp) | | {fmt(g2, w=m.window)} | FT better in {(g2 < 0).mean() * 100:.0f}% of pairs |"]

# ---- variants on the same (ticker, window) pairs: log-return input, temperature, lookback, samples
var = {"lr": "log-return input", "t05": "temperature 0.5", "lb200": "lookback 200", "lb100": "lookback 100", "s20": "20 samples", "realdates": "real trading dates for y_timestamp", "lr40": "log-return input, all 40 windows"}
rows4 = []
for tag, label in var.items():
    f = BASE / f"results/rolling/paths_{tag}.csv"
    if not f.exists():
        continue
    v = pd.read_csv(f)
    m = d.merge(v[["ticker", "window"] + [f"pred_{i}" for i in range(PRED_LEN)]], on=["ticker", "window"], suffixes=("", "_v"))
    PV = m[[f"pred_{i}_v" for i in range(PRED_LEN)]].to_numpy()
    Am = m[[f"act_{i}" for i in range(PRED_LEN)]].to_numpy()
    vm = pd.Series((np.abs(PV - Am) / Am).mean(1) * 100)
    vd = pd.Series((np.sign(PV[:, -1] / m.last_ctx_close - 1) == np.sign(m.act_ret)) * 100)
    w = m.window.to_numpy()
    lo = lambda x: ci(x, w=w)
    gap2 = vm - m.mape.reset_index(drop=True)
    rows4.append(f"| {label} | {len(m)} | {m.mape.mean():.2f} | {vm.mean():.2f} | {gap2.mean():+.2f} [{lo(gap2)[0]:+.2f}, {lo(gap2)[1]:+.2f}] | {m.naive_mape.mean():.2f} | {m.dir_hit.mean():.1f} | {vd.mean():.1f} |")
if rows4:
    out += ["", "## 4. Variants vs default zero-shot (same pairs)\n",
            "| Variant | Pairs | Default MAPE % | Variant MAPE % | Variant - default (pp) | Naive MAPE % | Default dir % | Variant dir % |",
            "|---|---|---|---|---|---|---|---|"] + rows4

p = BASE / "results/analysis/rolling_report.md"
p.write_text("\n".join(out) + "\n")
print("\n".join(out[:12 + 0]))
print("\n".join(l for l in out if l.startswith("| Equal") or l.startswith("| Kronos") or l.startswith("| 5d") or l.startswith("Kronos long-only minus")))
